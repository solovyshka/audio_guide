QA_BASE = """
Ты QA-редактор аудиогида. Сверяй CityGuide с Research.

valid=false ТОЛЬКО если есть существенное:
- факт, дата, имя, легенда или число, которых нет в research;
- остановка описывает чужой объект;
- последняя точка ведёт дальше по маршруту;
- следующая точка в финале не из маршрута;
- выдуманы часы, цены или время перехода;
- число остановок не соответствует заданному формату гида.

Не считай ошибкой и не включай в errors:
- перефразированные названия (площадь / мемориал на ней);
- стиль, порядок фраз, «характер архитектуры» без конкретной даты;
- мелкие уточнения, которые ты сам называешь несущественными.

Если сомневаешься — valid=true и errors пустой.
""".strip()

FIX_BASE = """
Исправь CityGuide по QA.
Не добавляй новых фактов. Используй только Research.
Не меняй id, name, lat, lon, category или order.
Спорное из disputed оставляй в тексте с «— неизвестно».
Если точка описывает чужой объект — полностью перепиши её текст
из facts/dates/people этой же остановки research. Старый абзац не оставляй.
Последняя точка: только свой объект, маршрут здесь заканчивается.
Не меняй число остановок: короткий и длинный формат заданы заранее.
""".strip()


def research_system(length: str = SHORT) -> str:
    spec = profile(length)
    return f"{RESEARCH_BASE}\n\n{spec.research_block}"


def writer_system(length: str = SHORT) -> str:
    spec = profile(length)
    return f"{WRITER_BASE}\n\n{spec.writer_block}"


def qa_system(length: str = SHORT) -> str:
    spec = profile(length)
    extra = (
        f"Формат гида: {spec.label.upper()}. "
        f"Ожидай {spec.min_stops}–{spec.max_stops} остановок, "
        f"{spec.min_sentences}–{spec.max_sentences} предложений на точку."
    )
    return f"{QA_BASE}\n\n{extra}"


def fix_system(length: str = SHORT) -> str:
    spec = profile(length)
    extra = (
        f"Формат: {spec.label}. Сохрани {spec.min_stops}–{spec.max_stops} остановок, "
        f"{spec.min_sentences}–{spec.max_sentences} предложений и примерно "
        f"{spec.min_stop_chars}–{spec.max_stop_chars} знаков."
    )
    return f"{FIX_BASE}\n{extra}"


RESEARCH_SYSTEM = research_system(SHORT)
WRITER_SYSTEM = writer_system(SHORT)
QA_SYSTEM = qa_system(SHORT)
FIX_SYSTEM = fix_system(SHORT)

